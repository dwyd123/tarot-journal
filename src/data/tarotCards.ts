function createSuitCards(
  suitId: string,
  suitZh: TarotSuit,
  suitEn: string,
): TarotCardDefinition[] {
  return MINOR_RANKS.map((rank) => ({
    cardId: `${suitId}-${rank.idPart}`,
    nameZh: `${suitZh}${rank.nameZh}`,
    nameEn: `${rank.nameEn} of ${suitEn}`,
    arcana: "小阿尔卡那",
    suit: suitZh,
    rank: rank.rank,
    displayNumber: rank.displayNumber,
    imagePath: null,
  }));
}

